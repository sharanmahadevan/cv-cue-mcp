#!/usr/bin/env python3
"""
Regenerate docs/src/content/docs/reference/tools.md from the server's real tool
definitions, so the reference can't drift from the code.

    python scripts/gen_tool_docs.py
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from cvcue_mcp.hosted import HostedSettings, build_app  # noqa: E402
from cvcue_mcp.web.store import Cipher  # noqa: E402

OUT = ROOT / "docs" / "src" / "content" / "docs" / "reference" / "tools.md"

GROUPS = [
    ("Session and system", ["cvcue_session_info", "cvcue_server_info"]),
    ("Connections (hosted, signed-in users)", ["cvcue_list_connections", "cvcue_use_connection"]),
    ("Locations", ["cvcue_list_locations", "cvcue_get_location", "cvcue_create_location", "cvcue_delete_location"]),
    ("Access points", ["cvcue_list_aps", "cvcue_get_ap", "cvcue_ap_health_summary", "cvcue_list_radios",
                       "cvcue_reboot_aps"]),
    ("Clients", ["cvcue_list_clients", "cvcue_find_client", "cvcue_client_health_summary",
                 "cvcue_client_association_history", "cvcue_disconnect_client"]),
    ("SSIDs", ["cvcue_list_ssids", "cvcue_get_ssid", "cvcue_ssid_usage", "cvcue_delete_ssid"]),
    ("Events and WIPS", ["cvcue_query_events", "cvcue_event_summary", "cvcue_list_rogue_aps",
                         "cvcue_rogue_ap_summary"]),
    ("Troubleshooting", ["cvcue_network_health", "cvcue_client_events", "cvcue_device_logs",
                         "cvcue_troubleshoot_client"]),
    ("Wired", ["cvcue_list_switches", "cvcue_list_wired_clients"]),
    ("Full API discovery", ["cvcue_api_modules", "cvcue_api_search", "cvcue_api_schema", "cvcue_api_execute"]),
    ("Endpoint notes", ["cvcue_save_endpoint_note", "cvcue_delete_endpoint_note"]),
]
WRITES = {"cvcue_create_location", "cvcue_delete_location", "cvcue_reboot_aps", "cvcue_disconnect_client",
          "cvcue_delete_ssid"}
CONFIRM = {"cvcue_delete_location", "cvcue_reboot_aps", "cvcue_disconnect_client", "cvcue_delete_ssid"}


def _type(schema: dict) -> str:
    if "anyOf" in schema:
        return " \\| ".join(_type(s) for s in schema["anyOf"] if s.get("type") != "null") or "any"
    t = schema.get("type", "any")
    if t == "array":
        return f"{_type(schema.get('items', {}))}[]"
    return {"integer": "int", "number": "number", "boolean": "bool", "string": "string", "object": "object"}.get(t, t)


async def collect() -> dict:
    """List tools from the hosted app's FastMCP instance (a superset of local mode)."""
    app = build_app(HostedSettings(master_key=Cipher.generate_key(), session_secret="x", db_path=":memory:"))
    return {t.name: t for t in await app.mcp.list_tools()}


def render(tools: dict) -> str:
    out = [
        "---",
        "title: Tools",
        "description: Every tool the CV-CUE MCP server exposes, with parameters. Generated from the code.",
        "---",
        "",
        ":::note",
        "This page is generated by `scripts/gen_tool_docs.py` from the server's own tool definitions.",
        ":::",
        "",
        "✎ marks a tool that changes your network. It only runs when writes are enabled for the connection;",
        "🔒 tools also need `confirm=true`.",
        "",
    ]
    for group, names in GROUPS:
        out += [f"## {group}", ""]
        for n in names:
            t = tools[n]
            mark = (" ✎" if n in WRITES else "") + (" 🔒" if n in CONFIRM else "")
            out += [f"### `{n}`{mark}", ""]
            desc = " ".join((t.description or "").split())
            props = t.inputSchema.get("properties", {})
            req = set(t.inputSchema.get("required", []))
            rows = [(k, _type(v), "required" if k in req else f"`{v.get('default')!r}`" if "default" in v else "",
                     " ".join((v.get("description") or "").split())) for k, v in props.items()]
            out += [desc, ""]
            if rows:
                out += ["| Parameter | Type | Default | Description |", "|---|---|---|---|"]
                pipe = "\\|"
                out += [f"| `{a}` | {b} | {'**required**' if c == 'required' else c} | {d.replace('|', pipe)} |"
                        for a, b, c, d in rows]
            else:
                out += ["_No parameters._"]
            out += [""]
    return "\n".join(out)


def main() -> None:
    tools = asyncio.run(collect())
    missing = [n for _, ns in GROUPS for n in ns if n not in tools]
    extra = sorted(set(tools) - {n for _, ns in GROUPS for n in ns})
    if missing or extra:
        raise SystemExit(f"Update GROUPS: missing={missing} unlisted={extra}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(tools))
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(tools)} tools)")


if __name__ == "__main__":
    main()
